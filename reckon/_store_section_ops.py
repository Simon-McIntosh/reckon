"""Set one field of an existing plan section through ``edit_plan``.

A section carries two kinds of field, and they are written differently.

Its typed metadata — ``links``, ``effort_hours`` and ``capability`` — is
regenerated by the state writer from the record the write carries, so setting
one of those changes only the working state; the record element on the page is
rewritten from it on the way out.

Its authored text — the ``h2`` title and the prose body — is HTML the state
writer preserves untouched. Setting either queues an authored-HTML edit that the
same write consumes, applied through the one replacement path the text editor
uses, so the section's review fingerprint keeps its one form and the write owes
the same review a hand replacement would.

The five accepted fields are named by a refusal for both an unknown field and a
status, which stays with ``section_declarations.<id>``.
"""

from __future__ import annotations

from contextvars import ContextVar
from typing import Any

#: The fields ``sections.<id>.<field>`` accepts, in the order a refusal lists them.
SECTION_SET_FIELDS: tuple[str, ...] = (
    "title",
    "links",
    "effort_hours",
    "capability",
    "body",
)

#: The prefix a section's set path carries.
SECTION_PATH_HEAD = "sections"

#: Fields the state writer renders from the store as a typed record.
_RECORD_FIELDS = frozenset({"links", "effort_hours", "capability"})

#: Fields carried by authored HTML rather than by the typed record.
_AUTHORED_FIELDS = frozenset({"title", "body"})

#: The keys of a ``SectionRecord``, so a record read back from a plan validates
#: through the same model an insert builds one from.
_RECORD_KEYS = ("id", "effort_hours", "capability", "attempts", "status", "links")

#: The path a section's status is written through; named in the refusal of the
#: ``sections.<id>.status`` spelling this handler does not accept.
DECLARATION_PATH = "section_declarations.<id>"

#: Queued authored edits, held by identity of the working dict that produced
#: them, exactly as the section-insertion and evidence-append effects are.
_SECTION_FIELD_EDITS: ContextVar[tuple[dict, list[dict[str, str]]] | None] = ContextVar(
    "reckon_section_field_edits", default=None
)


def _op_error(message: str):
    """Build an ``OpError`` without importing the store at module load, which
    would close an import cycle: the store imports this module for its handler."""
    from reckon._store import OpError

    return OpError(message)


def begin_section_field_edits(working: dict) -> None:
    """Start an empty authored-section-edit collection for one op batch."""
    _SECTION_FIELD_EDITS.set((working, []))


def _queue_section_field_edit(working: dict, request: dict[str, str]) -> None:
    """Attach one authored title/body edit to the current batch."""
    pending = _SECTION_FIELD_EDITS.get()
    if pending is None or pending[0] is not working:
        raise _op_error(
            "set sections.<id>.title/body has no active write-effect collection"
        )
    pending[1].append(request)


def consume_section_field_edits(data: dict[str, Any]) -> list[dict[str, str]]:
    """Return effects produced by this exact state object, then clear them."""
    pending = _SECTION_FIELD_EDITS.get()
    if pending is None or pending[0] is not data:
        return []
    _SECTION_FIELD_EDITS.set(None)
    return list(pending[1])


def _accepted_fields_message(section_id: str) -> str:
    return (
        f"sections.{section_id}.<field> accepts {', '.join(SECTION_SET_FIELDS)}; "
        "a section's status is a declaration — set "
        f"{DECLARATION_PATH} instead"
    )


def _refuse_forged_structure(section_id: str, body: str) -> None:
    """Refuse a body that would forge a heading or a structured section."""
    from bs4 import BeautifulSoup

    from reckon import _plan_html

    if _plan_html.plan_headings(body):
        raise _op_error(
            f"sections.{section_id}.body must not contain a heading: a body is "
            "authored prose, and a heading inside it would forge a section"
        )
    if BeautifulSoup(body, "html.parser").select_one(
        f"section[{_plan_html.RECKON_ATTRIBUTE}]"
    ):
        raise _op_error(
            f"sections.{section_id}.body must not contain a structured section "
            f"element ({_plan_html.RECKON_ATTRIBUTE})"
        )


def _require_authored_value(section_id: str, field: str, value: Any) -> str:
    """Return a validated authored title/body value or refuse it."""
    if not isinstance(value, str):
        raise _op_error(f"sections.{section_id}.{field} must be a string")
    if field == "title" and not value.strip():
        raise _op_error(f"sections.{section_id}.title must be a non-empty string")
    if field == "body":
        _refuse_forged_structure(section_id, value)
    return value


def _validated_record(record: dict, field: str, value: Any) -> dict:
    """Apply one record field to a section's typed record, validating it whole.

    Validation runs through the same ``SectionRecord`` an ``insert_section``
    builds a record from, so a field the schema refuses is refused here in the
    same words, and the record the writer renders stays one shape.
    """
    from pydantic import ValidationError

    from reckon._schema import SectionRecord
    from reckon._store import _section_contract_refusal

    candidate = {key: record[key] for key in _RECORD_KEYS if key in record}
    candidate[field] = value
    try:
        return SectionRecord.model_validate(candidate).model_dump(
            by_alias=True, exclude_none=True
        )
    except ValidationError as exc:
        raise _op_error(_section_contract_refusal(str(exc))) from exc


def _section_by_id(sections: Any, section_id: str) -> tuple[int, dict] | None:
    if not isinstance(sections, list):
        return None
    for index, record in enumerate(sections):
        if isinstance(record, dict) and str(record.get("id") or "") == section_id:
            return index, record
    return None


def apply_section_field_set(
    working: dict, parts: list[str], value: Any, warnings: list[str]
) -> None:
    """Handle one ``set sections.<id>.<field>`` op against the working state."""
    if len(parts) != 3:
        raise _op_error(
            "set sections requires the form sections.<id>.<field>; "
            f"the accepted fields are {', '.join(SECTION_SET_FIELDS)}"
        )
    section_id, field = parts[1], parts[2]
    if field == "status":
        raise _op_error(
            f"sections.{section_id}.status is not settable: a section's status is "
            f"a declaration — set {DECLARATION_PATH} to move it"
        )
    if field not in SECTION_SET_FIELDS:
        raise _op_error(_accepted_fields_message(section_id))
    hit = _section_by_id(working.get("sections"), section_id)
    if hit is None:
        raise _op_error(
            f"plan has no section {section_id!r}: sections.{section_id}.{field} "
            "names a section the plan does not carry"
        )
    index, record = hit
    if field in _AUTHORED_FIELDS:
        _queue_section_field_edit(
            working,
            {
                "id": section_id,
                "field": field,
                "value": _require_authored_value(section_id, field, value),
            },
        )
        return
    sections = working["sections"]
    sections[index] = _validated_record(record, field, value)


def _preserve_body_edges(original: str, value: str) -> str:
    """Write a new body between the whitespace and indentation it already sits in.

    The surrounding newlines, indentation and blank lines belong to the document
    layout rather than to the prose, so they are kept and only the authored span
    between them is replaced.
    """
    stripped = value.strip()
    if not original.strip():
        return original + stripped
    lead = original[: len(original) - len(original.lstrip())]
    trail = original[len(original.rstrip()) :]
    return f"{lead}{stripped}{trail}"


def apply_section_field_edits(
    html_text: str, requests: list[dict[str, str]], *, replace
) -> str:
    """Apply queued authored title/body edits to ``html_text``, in order.

    Each edit is located by the section's own heading, so the preimage is the
    bytes the document carries rather than a fragment a caller retyped — an
    entity such as ``&#x27;`` in the stored prose cannot make the match miss.
    ``replace`` is the store's authored-fragment replacement, passed in so this
    module and the text editor share one replacement path rather than two.
    """
    from reckon import _plan_html

    for request in requests:
        section_id = request["id"]
        field = request["field"]
        spans = _plan_html.section_field_spans(html_text, section_id)
        if spans is None:
            raise _op_error(
                f"plan has no authored heading for section {section_id!r}; "
                f"sections.{section_id}.{field} was accepted but the heading is gone"
            )
        title_span, body_span = spans
        start, end = title_span if field == "title" else body_span
        original = html_text[start:end]
        if field == "title":
            from html import escape

            replacement = escape(request["value"])
        else:
            replacement = _preserve_body_edges(original, request["value"])
        html_text = replace(
            html_text,
            original,
            replacement,
            selector_name=f"sections.{section_id}.{field}",
        )
    return html_text
