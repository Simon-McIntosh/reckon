def dispatch_module():
    return importlib.import_module("reckon.crew.dispatch")


def test_every_original_binding_resolves_to_its_home():
    facade = dispatch_module()
    for name in EXPECTED_SURFACE:
        assert hasattr(facade, name), f"missing dispatch re-export: {name}"
        homes = [
            module_name
            for module_name, exports in facade._MODULE_EXPORTS.items()
            if name in exports
        ]
        assert len(homes) == 1, f"ambiguous or missing dispatch home: {name}"
        home = importlib.import_module(f"reckon.crew.dispatching.{homes[0]}")
        assert getattr(facade, name) is getattr(home, name), name


def test_facade_patch_reaches_every_concern_that_reads_it(monkeypatch):
    facade = dispatch_module()
    for name in EXPECTED_SURFACE:
        readers = [
            module for module in facade._CONCERN_MODULES if hasattr(module, name)
        ]
        original = getattr(facade, name)
        sentinel = object()
        with monkeypatch.context() as patch:
            patch.setattr(facade, name, sentinel)
            assert getattr(facade, name) is sentinel
            for module in readers:
                assert getattr(module, name) is sentinel, f"{module.__name__}.{name}"
        assert getattr(facade, name) is original
        for module in readers:
            assert getattr(module, name) is original, f"{module.__name__}.{name}"


def test_patch_is_observed_by_moved_function(monkeypatch, tmp_path):
    facade = dispatch_module()
    monkeypatch.setattr(facade, "run_dir", lambda run_id: tmp_path / run_id)
    monkeypatch.setattr(facade, "ATTEMPT_RECORD_NAME", "attempt.receipt")
    assert facade._attempt_record_for("sample") == tmp_path / "sample/attempt.receipt"


def test_every_concern_fits_the_module_limit():
    package = importlib.import_module("reckon.crew.dispatching")
    modules = sorted(Path(package.__file__).parent.glob("*.py"))
    assert len(modules) > 1
    for source in modules:
        assert len(source.read_text().splitlines()) <= 2000, source.name


def test_cyclic_concern_bindings_are_the_facade_objects():
    facade = dispatch_module()
    for module in facade._CONCERN_MODULES:
        for name in getattr(module, "_FACADE_BINDINGS", ()):
            assert getattr(module, name) is getattr(facade, name), name
